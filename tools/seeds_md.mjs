/**
 * docs/SEEDS.md, read from chain: every canonical offer (the real incidents)
 * with its proofs, settlement and refunds, and the demo run with every
 * payout's proof. Inputs besides the chain: docs/seed-canonical.json,
 * docs/demo-run.json, docs/payouts.json, the keeper-state branch.
 *   node tools/seeds_md.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { client, deployments, balanceOf } from "./lib/wf.mjs";
import { txUrl } from "./lib/chains.mjs";

const root = new URL("..", import.meta.url);
const j = (p) => (existsSync(new URL(p, root)) ? JSON.parse(readFileSync(new URL(p, root), "utf8")) : null);
const dep = deployments().contracts;
const data = j("data/incidents.json");
const seed = j("docs/seed-canonical.json") ?? { incidents: {} };
const demo = j("docs/demo-run.json");
const payouts = j("docs/payouts.json") ?? { payouts: [] };
const ST = "https://explorer-studio-dev.genlayer.com";
const reg = dep.WhiteFlagRegistry.address, regDemo = dep.WhiteFlagRegistryDemo.address;
const C = client({ role: "keeper", address: reg });
const CD = client({ role: "keeper", address: regDemo });
let keeper = null;
try { keeper = await (await fetch("https://raw.githubusercontent.com/kenil1710/whiteflag/keeper-state/keeper-state.json", { cache: "no-store" })).json(); } catch { keeper = null; }

const gen = (w) => (Number(BigInt(w)) / 1e18).toFixed(6).replace(/\.?0+$/, "");
const pct = (ppm) => (ppm / 1e4).toFixed(4) + "%";
const short = (h) => h.slice(0, 10) + "…";
const iso = (t) => (t ? new Date(t * 1000).toISOString().slice(0, 19).replace("T", " ") + " UTC" : "-");
const amt = (wei, dec = 18) => { const s = BigInt(wei).toString().padStart(dec + 1, "0"); const f = s.slice(-dec).replace(/0+$/, "").slice(0, 4); return Number(s.slice(0, -dec)).toLocaleString("en-US") + (f ? "." + f : ""); };
async function proofsOf(cl, id) { const out = []; for (let off = 0; ;) { const p = await cl.view("get_proofs", [id, off, 50]); out.push(...p.items); if (p.next_offset === -1) return out; off = p.next_offset; } }
const keeperActs = (regAddr, id) => Object.values(keeper?.actions ?? {}).filter((a) => a.registry === regAddr.toLowerCase() && a.offer_id === id);

const L = [];
L.push("# Seeds", "");
L.push(`Generated by \`node tools/seeds_md.mjs\` from chain on ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC. Canonical registry [\`${reg}\`](${ST}/address/${reg}) (claim window 1 h), demo registry [\`${regDemo}\`](${ST}/address/${regDemo}) (claim window 3 min).`, "");
L.push("## Canonical: the real incidents", "");
L.push("Each incident in [FEASIBILITY.md](FEASIBILITY.md) is an offer with its real exploiter and recovery addresses, real stolen amounts, the real public bounty share and return window, and a symbolic 1 GEN bounty, opened by the seed's protocol account. Every real return transaction and every known non-return was submitted as a proof. Nobody holds the exploiters' keys, so no bounty is claimed: after the 1 h claim window the keeper refunds it.", "");
L.push("| Case | Incident | Outcome | Returned | Proofs (counted / rejected) | Bounty owed | Refunded at settlement | Refunded after the window | Why |", "|---|---|---|---|---|---|---|---|---|");
const rows = [];
for (const inc of data.incidents) {
  const id = seed.incidents[inc.id]?.offer_id;
  if (!id) continue;
  const o = await C.view("get_offer", [id]);
  const ps = await proofsOf(C, id);
  rows.push({ inc, o, ps });
  const why = o.status === "OPEN" ? `open until ${iso(o.settle_at)}`
    : o.status === "SETTLED_FULL" ? "every listed token came back in full before the deadline"
    : o.status === "SETTLED_NONE" ? "no transaction from an exploiter address reached a recovery address"
    : `returned ${pct(o.fraction_ppm)} of the weighted stolen value; the rest was kept`;
  L.push(`| #${String(inc.case_no).padStart(2, "0")} | [${inc.name}](https://whiteflag-ledger.vercel.app/incident/${id}) | ${o.status} | ${pct(o.fraction_ppm)} | ${o.n_counted} / ${o.n_rejected} | ${gen(o.owed)} GEN | ${gen(o.refunded_at_settle)} GEN | ${gen(o.unclaimed_refunded)} GEN | ${why} |`);
}
L.push("");
for (const { inc, o, ps } of rows) {
  L.push(`### #${String(inc.case_no).padStart(2, "0")} ${inc.name} (offer ${o.offer_id})`, "");
  L.push(`Offer window ${iso(o.start)} to ${iso(o.deadline)}, bounty share ${o.bounty_share_bps / 100}%, settle time ${iso(o.settle_at)}, status **${o.status}**${o.settled_at ? ` at ${iso(o.settled_at)}` : ""}.`, "");
  if (ps.length) {
    L.push("| Proof | Transaction | Verdict | Credited |", "|---|---|---|---|");
    for (const p of ps) {
      const sym = (t) => o.tokens.find((x) => x.chain === p.chain && x.token === t)?.symbol ?? t;
      L.push(`| #${p.proof_id} | [${p.chain} ${short(p.tx_hash)}](${txUrl(p.chain, p.tx_hash)}) | ${p.status === "COUNTED" ? "COUNTED" : "REJECTED " + p.reason} | ${p.credits.map((c) => `${amt(c.amount)} ${sym(c.token)}`).join(" + ") || "-"} |`);
    }
    L.push("");
  }
  const tok = o.tokens.map((t) => `${t.symbol} ${amt(o.returned[t.chain + ":" + t.token] ?? "0", t.decimals)} of ${amt(t.stolen, t.decimals)}`).join("; ");
  L.push(`Returned per token: ${tok}.`);
  if (o.history.length) L.push(`Protocol actions: ${o.history.map((h) => h.what === "recovery" ? `added recovery ${h.address} at ${iso(h.at)}` : `deadline ${iso(h.from)} -> ${iso(h.to)}`).join("; ")}.`);
  const tx = seed.incidents[inc.id]?.txs ?? [];
  if (tx.length) L.push(`Seed transactions: ${tx.map((t) => `[${t.fn}](${ST}/tx/${t.hash})`).join(", ")}.`);
  const ka = keeperActs(reg, o.offer_id);
  if (ka.length) L.push(`Keeper: ${ka.map((a) => `${a.action} ${a.status}${a.hashes?.length ? ` ([${short(a.hashes[a.hashes.length - 1])}](${ST}/tx/${a.hashes[a.hashes.length - 1]}))` : ""}${a.done_by_other ? " (done by another caller)" : ""}`).join(", ")}.`);
  L.push("");
}
const balC = await balanceOf(reg);
const sC = await C.view("get_stats");
L.push(`Canonical registry \`eth_getBalance\`: **${gen(balC)} GEN** (held by open offers and owed bounties: ${gen(sC.held)} GEN).`, "");

if (demo) {
  L.push("## Demo: every path", "");
  L.push(`Run by \`node test/demo_run.mjs\` on ${demo.started_at.slice(0, 16).replace("T", " ")} UTC; log: [demo-run.log](demo-run.log), record: [demo-run.json](demo-run.json). Demo offers list the real exploiter addresses plus a demo exploiter key, so claims can be signed; the returns are the same real transactions.`, "");
  L.push("| Offer | Path | Outcome |", "|---|---|---|");
  const label = { "A-full": "full return, settled early at 100%, claimed to a named payout address", "B-partial": "partial (Arbitrum FRAX), remainder refunded at settlement, stranger's claim refused, named payout refused under EXPLOITER_ONLY, claimed by the second exploiter address", "C-none": "nothing returned, whole bounty refunded at settlement, claim refused (nothing owed)", "D-refund-after-window": "partial, refund refused inside the window, claim refused after it, owed bounty refunded", "E-rejections": "every live rejection reason, duplicate and unsupported chain refused, deadline extended, stranger's extension refused, recovery address added" };
  for (const [k, id] of Object.entries(demo.offers)) {
    const o = await CD.view("get_offer", [id]);
    L.push(`| [${id}](https://whiteflag-ledger.vercel.app/incident/${id}?r=demo) | ${label[k] ?? k} | ${o.status} ${pct(o.fraction_ppm)}, owed ${gen(o.owed)}, paid ${gen(o.claimed)}${o.paid_to ? " to " + short(o.paid_to) : ""}, refunded ${gen(BigInt(o.refunded_at_settle) + BigInt(o.unclaimed_refunded))} GEN |`);
  }
  L.push("", "### Rejections produced live", "", "| Proof | Transaction | Reason |", "|---|---|---|");
  for (const r of demo.rejections ?? []) L.push(`| #${r.proof_id} | [${r.chain} ${short(r.tx)}](${txUrl(r.chain, r.tx)}) | ${r.status === "COUNTED" ? "COUNTED (kept as the duplicate's original)" : r.reason}${r.detail ? " (" + r.detail + ")" : ""} |`);
  L.push("", "Refused before reading (the call reverts, nothing recorded):", "");
  for (const s of demo.steps.filter((s) => !s.ok && /claim|duplicate|chain-not|extend-by|refund-inside/.test(s.label))) L.push(`- ${s.label}: \`${(s.reason || "").slice(0, 90)}\` ([tx](${ST}/tx/${s.hash}))`);
  L.push("", "### Gate states", "", "| Expected | Offer | State | Favorable |", "|---|---|---|---|");
  for (const g of demo.gate_states ?? []) L.push(`| ${g.expected} | ${g.offer ?? "A"} | ${g.state ?? "-"} | ${g.favorable} |`);
  L.push("", "### Payouts, each verified at the recipient", "", "| Payout | Amount (GEN) | Recipient | Transaction | Delivered | Registry Δ | Recipient Δ |", "|---|---|---|---|---|---|---|");
  for (const p of payouts.payouts) L.push(`| ${p.label} | ${gen(p.amount)} | \`${short(p.payee)}\` | [${short(p.tx)}](${ST}/tx/${p.tx}) | ${p.delivered && p.balances_ok ? "yes" : "NO: " + (p.why || p.balances_why)} | ${gen(p.registry_delta)} | ${gen(p.payee_delta)}${p.payee_paid_fee ? " (paid the fee)" : ""} |`);
  const balD = await balanceOf(regDemo);
  L.push("", `Demo registry \`eth_getBalance\` after the run: **${gen(balD)} GEN**.`, "");
}
writeFileSync(new URL("docs/SEEDS.md", root), L.join("\n") + "\n");
console.log("wrote docs/SEEDS.md");
